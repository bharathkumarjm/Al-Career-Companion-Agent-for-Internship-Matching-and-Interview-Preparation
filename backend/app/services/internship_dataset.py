def seed_internships_if_empty(db):
    """Seed the database with rich internship records if table is empty."""
    from app.models.internship import Internship

    existing_count = db.query(Internship).count()
    if existing_count == 0:
        demos = load_demo_internships()
        for item in demos:
            internship = Internship(
                title=item["title"],
                company=item.get("company", "TechCorp"),
                domain=item.get("domain", "Software Engineering"),
                description=item.get("description", ""),
                required_skills=item.get("required_skills", ""),
                preferred_skills=item.get("preferred_skills", ""),
                location=item.get("location", "Remote"),
                work_mode=item.get("work_mode", "Hybrid"),
                stipend=item.get("stipend", "Competitive"),
                duration=item.get("duration", "3-6 months"),
                education_requirements=item.get("education_requirements", ""),
                experience_requirements=item.get("experience_requirements", ""),
                responsibilities=item.get("responsibilities", ""),
                interview_process=item.get("interview_process", ""),
                status="active"
            )
            db.add(internship)
        db.commit()
        print(f"Seeded {len(demos)} internships into database.")
